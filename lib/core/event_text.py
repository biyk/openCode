# lib/core/event_text.py
"""Текст названий мероприятий для матчинга: очистка и разбиение.

Названия в календаре пишут «для человека»: со скобочными пометками,
эмодзи и составными пунктами («Завтрак. Принять витамины»). Матчингу
это только мешает, поэтому заголовок чистится (clean_title) и режется
по точкам (title_segments) — каждая часть оценивается отдельно, но
указывает на одно и то же мероприятие.
"""
from __future__ import annotations

import re

# Скобочные пометки любых видов: ( ) [ ] { }
_PAREN_RE = re.compile(r"\([^)]*\)|\[[^\]]*\]|\{[^}]*\}")
# Всё, что не буква/цифра/пробел (эмодзи, ▸, /, |, дефисы; точки
# остаются — на них работает разбиение)
_JUNK_RE = re.compile(r"[^\w\s.,;]", re.UNICODE)
# Слова-паразиты перед названием задачи в речи («я начал задачу починить…»)
NOISE_WORDS = {"задача", "задачу", "мероприятие", "дело", "к"}
# Местоимения/связки — не значимые слова для матчинга мероприятия
# («я почистил зубы» → ядро «почистил зубы»). Не путать с NOISE_WORDS:
# те срезаются только в начале, эти игнорируются по всему тексту.
STOP_TOKENS = {"я", "ты", "мы", "он", "она", "оно", "вы", "они",
               "мне", "меня", "мной", "моё", "мое", "мой", "моя",
               "это", "то", "и", "в", "на", "с", "у", "да"}
# Сокращения, после которых точка не разделяет пункт («2 шт.»)
ABBREV = {"шт"}
# Точка-разделитель составных пунктов — только с пробелом после
# («Завтрак. Принять витамины»); после «шт.» не режет; одиночные
# буквы-сокращения («т. д.») дают куски <2 символов и отбрасываются
_DOT_RE = re.compile(r"(?<!шт)\.(?=\s)")
# Запятая/точка с запятой с пробелом — тоже разделители пунктов
_COMMA_RE = re.compile(r"[,;]\s+")


def strip_noise(name: str) -> str:
    """Убирает ведущее слово-паразит («задачу помыть пол» → «помыть пол»)."""
    tokens = name.split()
    while tokens and tokens[0].lower().replace("ё", "е") in NOISE_WORDS:
        tokens = tokens[1:]
    return " ".join(tokens)


def clean_title(text: str) -> str:
    """Вырезает скобочные пометки и эмодзи из названия мероприятия."""
    text = _PAREN_RE.sub(" ", text or "")
    return _JUNK_RE.sub(" ", text)


def title_segments(title: str, min_len: int = 2) -> list[str]:
    """Части составного заголовка, каждый пункт — отдельная альтернатива.

    «Завтрак. Принять витамины» → ["завтрак", "принять витамины"].
    Точки сокращений («2 шт.») пункт не режут; пустые и однобуквенные
    обрывки отбрасываются.
    """
    cleaned = _COMMA_RE.sub(". ", clean_title(title))
    return [p.strip() for p in _DOT_RE.split(cleaned)
            if len(p.strip()) >= min_len]
