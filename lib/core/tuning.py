"""Центр настройки голосового ассистента: все порогы и лимиты в одном месте.

Каждая константа — это «ручка», которую крутят по ложным срабатываниям:
много ложных срабатываний → поднимаем порог строже (ассистент реже
угадывает и чаще молчит); слишком много промахов по реальным командам →
чуть опускаем. Числа вне этого файла не заводим — только здесь (с
комментарием, что ручка делает) и, где уместно, переопределением в
`targets/<hostname>/commands.json` (там тот же порог по своей секции).

JSON-конфиг комментариев не держит, поэтому смысл каждой величины описан
тут, у объявления. Пороги decision/dedup/shopping имеют пер-девайсный
оверрайд в commands.json; значения ниже — дефолт, когда в конфиге пусто.
"""

# ─── Laya: лимит вариантов и порог распознавания команд ────────────────────

# laya.max_opts: сервер не принимает больше вариантов в одном choice-вопросе
# (больше — HTTP 422). От этого числа зависят батчи (laya_batch, tasks_dedup).
LAYA_MAX_OPTS = 16

# Порог уверенности decision-слоя (уровень 2, «что просит сделать»).
# Поднят с 0.5 до 0.9: при 0.5 Лайя тянула бытовое прошедшее
# («я почистил зубы») к wakefix с c=0.61 и выполняла команду пробуждения.
# 0.6 ≈ «почти угадала» — для вызова действия этого мало: действуем только
# при высокой уверенности, иначе проходим дальше (event-match → opencode).
# Переопределяется в commands.json: decision.threshold.
DECISION_THRESHOLD = 0.9

# Порог бинарного вопроса event-match «начал или завершил» (2 варианта:
# start/complete). Здесь выбор из двух и уверенность по природе ниже, чем в
# 16-вариантном списке команд, поэтому порог мягче — но это отдельная ручка.
EVENT_ACTION_THRESHOLD = 0.4

# ─── Дедупликация задач (подтверждающий парный вопрос Лайи) ─────────────────

# Дубликатом считаем только уверенный ответ (c >= порога); ниже — новая
# задача. Калибровка: при низких c модель лепит дубли на несвязанные пары.
DEDUP_THRESHOLD = 0.9

# Вопрос по пачке-кандидату: годится любой выбор не none, порог не режет
# (уверенность на 15 вариантах шумная). Решение отдаёт парный вопрос выше.
DEDUP_BATCH_THRESHOLD = 0.0

# ─── Список покупок: нечёткое совпадение названия товара ────────────────────

# Порог похожести названий товаров (SequenceMatcher). Переопределяется в
# commands.json: shopping.dedup.threshold.
SHOPPING_DEDUP_THRESHOLD = 0.9

# ─── Нечёткое совпадение названия задачи/мероприятия (task_start) ───────────

# Похожесть строки-названия: ниже — не угадываем (концепция уровня 1).
# Основное средство против ложных привязок «я X к мероприятию Y».
TITLE_THRESHOLD = 0.75

# «Это же слово» по форме: общий корень длиной ≥ TOKEN_ROOT_PREFIX символов
# («почистить»/«почистил» → «почис») считается совпадением (вид/падеж).
TOKEN_ROOT_PREFIX = 5

# Мин. похожесть двух слов по SequenceMatcher, чтобы счесть их одним словом
# (ловит опечатки распознавания, когда общий корень не спасает).
TOKEN_RATIO = 0.80

# Сколько лучших кандидатов печатать в трассе event-match («название → score»)
# даже когда ни один не тянет выше порога: видно, сколько набрала фраза и
# почему не совпало (напр. «я позавтракал» vs «Завтрак. Принять витамины»). 0 — выкл.
EVENT_MATCH_DEBUG_TOP = 3
