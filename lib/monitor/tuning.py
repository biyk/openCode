# TOOLTIP: Дефолты монитора сервисов: heartbeat, просрочка, пробы портов, смотритель OmniRouter
# lib/monitor/tuning.py
"""Дефолты монитора сервисов.

Держимся здесь, а не в `lib/core/tuning.py`: тот упёрся в лимит 200 строк
(так же поступили с MIC_* в `lib/stt/mic_stream.py`). Пороги по-прежнему
переопределяются секцией `monitor` в targets/<host>/commands.json.
"""

# Heartbeat старше этого (сек) = основной процесс завис/умер и перестал писать
# пульс → все его сервисы в GUI красные. Запас ×3–4 от интервала сброса.
MONITOR_STALE_S = 8.0

# Как часто (сек) основной процесс сбрасывает снимок реестра в heartbeat-файл.
# Пишется атомарно (os.replace); дёшево — маленький JSON.
MONITOR_HEARTBEAT_S = 2.0

# Таймаут одной HTTP-пробы внешних процессов (Laya/браузер/доска).
MONITOR_PROBE_TIMEOUT_S = 1.0

# Адреса внешних процессов для проб: поднимаются не heartbeat'ом, а по факту
# порта. Laya — decision.url (дефолт :8080); браузер — CDP_PORT (9222);
# доска знаний — её сервер (:8765 по умолчанию). Панель монитора живёт
# именно на доске (вкладка «Сервисы»), отдельного сервера больше нет.
MONITOR_PROBE_LAYA_URL = "http://127.0.0.1:8080"
MONITOR_PROBE_CDP_PORT = 9222
MONITOR_BOARD_PORT = 8765

# OmniRouter (LLM-прокси, `lib/providers/omni.py`): порт и адрес пробы
# здоровья. Поднимает его собственный CLI — но не `restart` (тот не знает
# --daemon и крутил бы сервер в foreground), а `stop` + `serve --daemon`.
# /healthz, а не /api/health: это тот же 200, но дешевле (замер 16 мс против
# 38 мс) — он отвечает до маршрутизации Next.js и это рекомендация
# тестировщика шлюза (правило «TCP-коннекта недостаточно, решать по 200»).
MONITOR_OMNI_PORT = 20128
MONITOR_OMNI_URL = f"http://127.0.0.1:{MONITOR_OMNI_PORT}"
MONITOR_OMNI_HEALTH_PATH = "/healthz"

# Как часто смотритель опрашивает OmniRouter (сек) и сколько подряд неудачных
# ответов на открытом порту терпим (правило 3: проба раз в 30 с, считать
# только 3 неудачи подряд ≈ 90 с). Порт закрыт — процесс реально завершился,
# его поднимаем, не дожидаясь ответа health.
MONITOR_WATCHDOG_S = 30.0
MONITOR_OMNI_HANG_FAILS = 3

# И КАК ДОЛГО тишина тянется без единой успешной пробы. Только 90 с для
# «завис» мало: замерено живьём, что один штатный auto/smart-запрос глушит
# /healthz на 40–170 с (event loop node занят, а процесс здоров), так что
# «молчит 3 пробы» и «молчит 5 минут» — разные случаи. Раньше этого порога
# не было, и смотритель убивал работающий шлюз каждые ~3 минуты.
MONITOR_OMNI_HANG_AFTER_S = 300.0

# Сколько секунд после нашего перезапуска НЕ считать «зависшим» открытый порт
# без ответа. Измерено живьём: `serve --daemon` занимает порт через 0–6 с, а
# здоровье начинает отвечать только на ~45-й секунде (подъём Next.js).
# Прогрев заканчивается ПЕРВЫМ 200, а не по часам (правило 6): это потолок
# ожидания, а не обязательная пауза.
MONITOR_OMNI_WARMUP_S = 120.0

# Бэк-офф перезапусков (правило 5): пауза ПОСЛЕДОВАТЕЛЬНО нарастает 1 → 2 → 5
# → 15 → 60 с и сбрасывается, когда шлюз ожил. Замена прежнего «cooldown 180
# с»: фиксированная пауза сама по себе была тем самым циклом — смотритель
# перезапускал шлюз ровно каждые 180 с (интервалы в логе 187–202 с).
MONITOR_OMNI_BACKOFF_S = (1.0, 2.0, 5.0, 15.0, 60.0)

# Бюджет перезапусков (то же правило 5): не больше N за окно. По исчерпании
# смотритель процесс НЕ трогает — докладывает красным в панель и пишет в
# консоль/лог: цикл «умер → 35 с бут → снова умер» держит порт закрытым
# большую часть времени, а человек хотя бы узнает о причине.
MONITOR_OMNI_BUDGET_RESTARTS = 5
MONITOR_OMNI_BUDGET_WINDOW_S = 600.0

# Сколько секунд ждём, пока шлюз сам освободит порт после `stop` (правило 4:
# остановка только с дренажом). Больше этого не ждать нельзя и меньше нельзя:
# CLI `stop` на Windows опрашивает процесс 5 с, а потом SIGKILL’ует — свой
# SIGTERM detached-процессу отправить нечем (`POST /api/shutdown`
# требует авторизации: замерен 401), поэтому единственный честный дренаж —
# не убивать того, кто отвечает или занят.
MONITOR_OMNI_DRAIN_WAIT_S = 30.0

# Сколько секунд ждать сам CLI: `serve --daemon` возвращается сразу после
# spawn, `stop` опрашивает завершение процесса (до 5 с) — оба с запасом.
MONITOR_OMNI_RESTART_TIMEOUT_S = 90.0
MONITOR_OMNI_STOP_TIMEOUT_S = 20.0

# Сколько секунд после `serve --daemon` ждём открытого порта: spawn ещё не
# значит «сервер слушает», а докладывать «подняли», когда порт не открылся,
# — врать в панели.
MONITOR_OMNI_UP_WAIT_S = 30.0

# Таймаут пробы здоровья. Общий MONITOR_PROBE_TIMEOUT_S (1 с) годится для
# дешёвых проб страницы, но шлюз под нормальной нагрузкой (5686 моделей в
# combo) отвечает и 7 с, и 10 с — с таймаутом 3 с проба падала на 13 тактах из
# 18 при ОДНОМ auto/smart-запросе. 10 с — компромисс: зависший намертво
# процесс за ним тоже не ответит, а занятой переживёт.
MONITOR_OMNI_HEALTH_TIMEOUT_S = 10.0
